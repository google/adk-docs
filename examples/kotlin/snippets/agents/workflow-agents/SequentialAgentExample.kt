package com.google.adk.kt.examples.agents.workflowagents

// --8<-- [start:init]
import com.google.adk.kt.agents.Instruction
import com.google.adk.kt.agents.LlmAgent
import com.google.adk.kt.agents.SequentialAgent
import com.google.adk.kt.models.Gemini

// --- Constants ---
const val GEMINI_MODEL = "gemini-2.5-flash"

// --- 1. Define Sub-Agents for Each Pipeline Stage ---

// Code Writer Agent
// Takes the initial specification (from user query) and writes code.
val codeWriterAgent =
    LlmAgent(
        name = "CodeWriterAgent",
        model = Gemini(name = GEMINI_MODEL),
        instruction =
            Instruction(
                """
                You are a Kotlin Code Generator.
                Based *only* on the user's request, write Kotlin code that fulfills the requirement.
                Output *only* the complete Kotlin code block, enclosed in triple backticks (```kotlin ... ```).
                Do not add any other text before or after the code block.
                """.trimIndent(),
            ),
        description = "Writes initial Kotlin code based on a specification.",
        outputKey = "generated_code",
    )

// Code Reviewer Agent
// Takes the code generated by the previous agent (read from state) and provides feedback.
val codeReviewerAgent =
    LlmAgent(
        name = "CodeReviewerAgent",
        model = Gemini(name = GEMINI_MODEL),
        instruction =
            Instruction(
                """
                You are an expert Kotlin Code Reviewer.
                Your task is to provide constructive feedback on the provided code.

                **Code to Review:**
                ```kotlin
                {generated_code}
                ```

                **Review Criteria:**
                1.  **Correctness:** Does the code work as intended? Are there logic errors?
                2.  **Readability:** Is the code clear and easy to understand? Follows Kotlin coding conventions?
                3.  **Efficiency:** Is the code reasonably efficient? Any obvious performance bottlenecks?
                4.  **Edge Cases:** Does the code handle potential edge cases or invalid inputs gracefully?
                5.  **Best Practices:** Does the code follow common Kotlin best practices?

                **Output:**
                Provide your feedback as a concise, bulleted list. Focus on the most important points for improvement.
                If the code is excellent and requires no changes, simply state: "No major issues found."
                Output *only* the review comments or the "No major issues" statement.
                """.trimIndent(),
            ),
        description = "Reviews code and provides feedback.",
        outputKey = "review_comments",
    )

// Code Refactorer Agent
// Takes the original code and the review comments (read from state) and refactors the code.
val codeRefactorerAgent =
    LlmAgent(
        name = "CodeRefactorerAgent",
        model = Gemini(name = GEMINI_MODEL),
        instruction =
            Instruction(
                """
                You are a Kotlin Code Refactoring AI.
                Your goal is to improve the given Kotlin code based on the provided review comments.

                **Original Code:**
                ```kotlin
                {generated_code}
                ```

                **Review Comments:**
                {review_comments}

                **Task:**
                Carefully apply the suggestions from the review comments to refactor the original code.
                If the review comments state "No major issues found," return the original code unchanged.
                Ensure the final code is complete, functional, and includes necessary imports and KDoc comments.

                **Output:**
                Output *only* the final, refactored Kotlin code block, enclosed in triple backticks (```kotlin ... ```).
                Do not add any other text before or after the code block.
                """.trimIndent(),
            ),
        description = "Refactors code based on review comments.",
        outputKey = "refactored_code",
    )

// --- 2. Create the SequentialAgent ---
// This agent orchestrates the pipeline by running the subAgents in order.
val codePipelineAgent =
    SequentialAgent(
        name = "CodePipelineAgent",
        subAgents = listOf(codeWriterAgent, codeReviewerAgent, codeRefactorerAgent),
        description = "Executes a sequence of code writing, reviewing, and refactoring.",
    )

val rootAgent = codePipelineAgent
// --8<-- [end:init]
